#!/usr/bin/env python
"""Build a viewer-ready, measured city GLB from a dense reconstruction run.

The previous city_textured.glb was generated by an untracked ad-hoc script
that laid the model on its side (Z-up data in a Y-up glTF container), filled
unobserved geometry with bilateral-symmetry reflections and invented minarets,
and textured the whole scene from one facade photo.

This exporter:

  * reads the measured multi-view mesh (dense/mesh.obj) and fused cloud,
  * rotates the scene to gravity with a RANSAC ground plane,
  * writes a true glTF Y-up GLB with per-vertex colours,
  * keeps a backup of any existing city_textured.glb untouched.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

import numpy as np
import open3d as o3d
from scipy.spatial import cKDTree

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from uav3d.dense.glb_export import write_glb  # noqa: E402


def _align_gravity_from_cloud(cloud_path: Path) -> tuple[np.ndarray, float]:
    """PCA-based gravity alignment from the fused cloud.

    The cloud footprint is much larger than the building height, so the principal
    axis of smallest variance is the vertical axis. RANSAC plane fitting is
    unreliable on a messy MVS cloud: it can snap to a facade or a roof and lay
    the model on its side. This returns the rotation mapping "up" to +Z and the
    offset that puts the ground plane at z=0.
    """
    cloud = o3d.io.read_point_cloud(str(cloud_path))
    pts = np.asarray(cloud.points)
    if len(pts) < 100:
        return np.eye(3), 0.0
    probe = o3d.geometry.PointCloud()
    probe.points = o3d.utility.Vector3dVector(pts)
    down = probe.voxel_down_sample(0.25)
    if len(down.points) < 50:
        return np.eye(3), 0.0
    pts_d = np.asarray(down.points)
    centre = pts_d.mean(axis=0)
    c = pts_d - centre
    cov = c.T @ c / max(len(c), 1)
    _w, v = np.linalg.eigh(cov)  # ascending eigenvalues
    up = v[:, 0]  # smallest variance -> vertical
    h = pts_d @ up
    p5, med, p95 = np.percentile(h, [5, 50, 95])
    if (p95 - med) < (med - p5):
        up = -up
        p5 = float(np.percentile(pts_d @ up, 5))
    target = np.array([0.0, 0.0, 1.0])
    axis = np.cross(up, target)
    s = np.linalg.norm(axis)
    if s > 1e-6:
        skew = np.array(
            [
                [0.0, -axis[2], axis[1]],
                [axis[2], 0.0, -axis[0]],
                [-axis[1], axis[0], 0.0],
            ]
        )
        R = np.eye(3) + skew + skew @ skew * ((1.0 - up @ target) / (s * s + 1e-9))
    else:
        R = np.eye(3) if up @ target > 0 else -np.eye(3)
    return R, -float(p5)


def _simplify(mesh: o3d.geometry.TriangleMesh, target: int) -> o3d.geometry.TriangleMesh:
    if len(mesh.triangles) <= target:
        return mesh
    try:
        return mesh.simplify_quadric_decimation(target_number_of_triangles=target)
    except Exception:
        return mesh


def _mesh_colors_from_cloud(cloud_path: Path, rot: np.ndarray, offset: float, vertices: np.ndarray) -> np.ndarray:
    cloud = o3d.io.read_point_cloud(str(cloud_path))
    pts = np.asarray(cloud.points)
    cols = np.asarray(cloud.colors)
    if len(pts) == 0 or len(cols) != len(pts):
        return np.full_like(vertices, 0.75)
    pts_up = pts @ rot.T
    pts_up[:, 2] += offset
    tree = cKDTree(pts_up)
    _, idx = tree.query(vertices, workers=-1)
    return np.clip(cols[idx], 0.0, 1.0)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--run-dir", required=True, help="Path to a completed uav3d run directory")
    ap.add_argument("--out", default=str(ROOT / "city_textured.glb"), help="Output GLB path")
    ap.add_argument("--max-faces", type=int, default=400_000, help="Target triangle count")
    ap.add_argument("--scale", type=float, default=None, help="Metres per SfM unit (optional)")
    ap.add_argument("--mesh-path", default=None, help="Explicit mesh.obj path (overrides run dir lookup)")
    ap.add_argument("--cloud-path", default=None, help="Explicit cloud.ply path (overrides run dir lookup)")
    args = ap.parse_args()

    run = Path(args.run_dir)
    if args.mesh_path:
        mesh_path = Path(args.mesh_path)
    else:
        mesh_path = run / "dense" / "mesh.obj"
        if not mesh_path.exists():
            mesh_path = run / "dense_v2" / "mesh.obj"
    if args.cloud_path:
        cloud_path = Path(args.cloud_path)
    else:
        cloud_path = run / "dense" / "cloud.ply"
        if not cloud_path.exists():
            cloud_path = run / "dense_v2" / "cloud.ply"
    if not mesh_path.exists():
        sys.exit(f"Measured mesh not found at {run/'dense'/'mesh.obj'} or {run/'dense_v2'/'mesh.obj'}; run 'uav3d dense' first.")

    mesh = o3d.io.read_triangle_mesh(str(mesh_path))
    if len(mesh.triangles) == 0:
        sys.exit("Empty measured mesh.")
    mesh = _simplify(mesh, args.max_faces)

    verts = np.asarray(mesh.vertices, dtype=np.float64)
    faces = np.asarray(mesh.triangles, dtype=np.int64)
    R, offset = _align_gravity_from_cloud(cloud_path)
    verts_up = verts @ R.T
    verts_up[:, 2] += offset

    colors = _mesh_colors_from_cloud(cloud_path, R, offset, verts_up)
    lo = np.percentile(verts_up, 2.0, axis=0)
    hi = np.percentile(verts_up, 98.0, axis=0)
    verts_up[:, 0] -= 0.5 * (lo[0] + hi[0])
    verts_up[:, 1] -= 0.5 * (lo[1] + hi[1])
    verts_up[:, 2] -= lo[2]
    if args.scale:
        verts_up = verts_up * float(args.scale)

    out = Path(args.out)
    if out.exists():
        backup = out.with_name(out.stem + "_original" + out.suffix)
        if not backup.exists():
            shutil.copy2(out, backup)
            print(f"Backed up existing output to {backup}")

    write_glb(out, verts_up, faces, colors=colors, name="city_measured")

    mesh_out = o3d.geometry.TriangleMesh()
    mesh_out.vertices = o3d.utility.Vector3dVector(verts_up)
    mesh_out.triangles = o3d.utility.Vector3iVector(faces.astype(np.int32))
    mesh_out.vertex_colors = o3d.utility.Vector3dVector(np.clip(colors, 0.0, 1.0))
    ply_out = out.with_suffix(".ply")
    o3d.io.write_triangle_mesh(str(ply_out), mesh_out)

    print(
        json.dumps(
            {
                "out": str(out),
                "ply": str(ply_out),
                "vertices": int(len(verts_up)),
                "faces": int(len(faces)),
                "bbox": np.round(verts_up.min(0), 2).tolist(),
                "bbox_max": np.round(verts_up.max(0), 2).tolist(),
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()